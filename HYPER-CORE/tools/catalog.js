/* Writes <DISCIPLINE>/catalog.js: the id, title, summary and branch of every node,
 * so the other disciplines can show proper titles on links into this one and find
 * its concepts in search.
 *
 *   node HYPER-CORE/tools/catalog.js HYPER-MATH
 *   node HYPER-CORE/tools/catalog.js --all
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { makeContext, loadCore, run } = require('./load');

const ROOT = path.join(__dirname, '..', '..');
const DISCS = { 'HYPER-PHYSICS': 'physics', 'HYPER-MATH': 'math', 'HYPER-ELECTRONICS': 'electronics', 'HYPER-CHEMISTRY': 'chemistry' };
const args = process.argv.slice(2);
const targets = args.includes('--all') ? Object.keys(DISCS).filter(d => fs.existsSync(path.join(ROOT, d, 'content'))) : args.map(a => path.basename(path.resolve(a)));

for (const folder of targets) {
  const disc = DISCS[folder];
  if (!disc) { console.error('Not a Hyper discipline: ' + folder); continue; }
  const dir = path.join(ROOT, folder, 'content');
  const ctx = makeContext();
  const H = loadCore(ctx);
  H.use(disc);
  const list = fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort((a, b) => (a === 'outline.js' ? -1 : b === 'outline.js' ? 1 : a.localeCompare(b)));
  for (const f of list) { try { run(ctx, path.join(dir, f)); } catch (e) { console.error(folder + '/content/' + f + ': ' + e.message); } }
  H.build();
  const rows = H.order.map(id => {
    const n = H.nodes.get(id);
    const b = n.branch && n.branch !== id ? H.nodes.get(n.branch).title : '';
    const short = H.plain(n.short || '').slice(0, 220);
    // links into other disciplines, so they can show "used in" the other way round
    const xrefs = [...new Set(n.prereq.concat(n.related).filter(r => r.includes(':')))];
    return xrefs.length ? [id, n.title, short, b, xrefs] : [id, n.title, short, b];
  });
  // planned concepts not written yet still get their titles, so links read well meanwhile
  for (const n of H.list) for (const [id, title] of (n.plan || [])) {
    if (H.nodes.has(id)) continue;
    const b = n.branch ? H.nodes.get(n.branch).title : '';
    rows.push([id, title, '', b]);
  }
  const out = '/* ' + folder + '/catalog.js — generated by HYPER-CORE/tools/catalog.js; do not edit.\n' +
    ' * The titles of this discipline, for links and search in the other Hyper apps. */\n' +
    'Hyper.catalog(' + JSON.stringify(disc) + ', [\n' + rows.map(r => '  ' + JSON.stringify(r)).join(',\n') + '\n]);\n';
  fs.writeFileSync(path.join(ROOT, folder, 'catalog.js'), out);
  console.log(folder + '/catalog.js: ' + rows.length + ' entries');
}
