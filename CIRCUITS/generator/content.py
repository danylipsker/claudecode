def apply(cir, name):
    """Lay the page content out below and beside the schematic."""
    d = C.get(name)
    if not d:
        return
    y = NOTES_Y
    if d.get("notes"):
        cir.text((NOTES_X, y), d["notes"], 13, "#c8d8c8")
        y += 13 * len(d["notes"]) + 30
    if d.get("formulas"):
        cir.text((NOTES_X, y), d["formulas"], 14, "#ffe08a")
        y += 14 * len(d["formulas"]) + 30
    if d.get("graph"):
        cir.text((NOTES_X, y), d["graph"], 12, "#9fb8c8")
        y += 12 * len(d["graph"]) + 26
    if d.get("quote"):
        cir.text((NOTES_X, y),
                 [d["quote"], "        -- Mims, 555 Timer IC Circuits"],
                 13, "#e8b8b8")
    ty = TABLE_Y
    for caption, cols in d.get("tables", []):
        widest = max(max(len(v) for v in col) for col in cols)
        ty = cir.table((TABLE_X, ty), caption, cols, 12,
                       col_w=max(88, 8 * widest + 24)) + 34
