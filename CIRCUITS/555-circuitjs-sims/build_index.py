"""Build index.html from 555-sims-links.md.

The links file is the source of truth; this turns it into a page you can open
and click. Run it after editing the markdown:

    python build_index.py
"""
import html
import re
from pathlib import Path

HERE = Path(__file__).parent
LINKS = HERE / "555-sims-links.md"
OUT = HERE / "index.html"

LINE = re.compile(r"^- \[(?P<title>[^\]]+)\]\((?P<url>[^)]+)\)\s*$")
TITLE = re.compile(r"^p\.(?P<page>\d+)\s*-\s*(?P<name>.+)$")


def read_links():
    items = []
    for line in LINKS.read_text(encoding="utf-8").splitlines():
        m = LINE.match(line)
        if not m:
            continue
        title = m.group("title").strip()
        t = TITLE.match(title)
        page = t.group("page") if t else ""
        name = t.group("name").strip() if t else title
        items.append((page, name, m.group("url")))
    return items


def card(page, name, url):
    badge = f'<span class="page">p.{html.escape(page)}</span>' if page else ""
    return (
        f'      <li><a class="sim" href="{html.escape(url, quote=True)}" '
        f'target="_blank" rel="noopener">{badge}'
        f'<span class="name">{html.escape(name)}</span></a></li>'
    )


def build():
    items = read_links()
    if not items:
        raise SystemExit(f"No links found in {LINKS.name}")
    cards = "\n".join(card(*i) for i in items)
    OUT.write_text(TEMPLATE.format(count=len(items), cards=cards), encoding="utf-8")
    print(f"{OUT.name}: {len(items)} circuits")


