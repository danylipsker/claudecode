/* Curves Workshop · tools/catalog.js
 *
 * Rebuilds data/catalog.js: the list of figure and section files the page must load, and
 * an index of every figure (id, section, page, title, steps, tools) and section, so the
 * home page, the gallery and the search work before any figure is built.
 *
 *   node tools/catalog.js
 */
const fs = require('fs');
const path = require('path');
const C = require('./load')();
const ROOT = C.ROOT;

const figureFiles = fs.readdirSync(path.join(ROOT, 'figures')).filter(f => f.endsWith('.js')).sort();
const sectionFiles = fs.existsSync(path.join(ROOT, 'data', 'sections')) ? fs.readdirSync(path.join(ROOT, 'data', 'sections')).filter(f => f.endsWith('.js')).sort() : [];

const figures = [];
for (const id of C.order) {
  const f = C.figures.get(id);
  let steps = 0, tools = [], practice = false;
  try {
    const sc = C.build(f);
    steps = sc.steps.length;
    tools = Array.from(new Set(sc.steps.map(s => s.tool)));
    practice = C.targets(sc).length > 0;
  } catch (e) { console.error('catalog: ' + id + ' does not build: ' + e.message); }
  figures.push({ id, fig: f.fig, part: f.part, caption: f.caption, section: f.section, page: f.page, title: f.title || '', tags: f.tags || [], steps, tools, practice });
}
figures.sort((a, b) => a.fig - b.fig || a.part.localeCompare(b.part));

const sections = C.manifest.sections.map(m => {
  const s = C.sections.get(m.id);
  return {
    id: m.id, title: m.title, pages: m.pages, group: m.group, figs: m.figs,
    figures: figures.filter(f => f.section === m.id).map(f => f.id),
    hasText: !!s,
    constructions: s && s.constructions ? s.constructions.length : 0,
    short: s ? String(s.description || '').replace(/\$[^$]*\$/g, ' ').replace(/\[\[([^\]|]+)(\|([^\]]+))?\]\]/g, (m, a, b, c) => c || a).replace(/[*_`]/g, '').split(/(?<=\.)\s/)[0].slice(0, 220) : ''
  };
});

const out = '/* Curves Workshop · data/catalog.js — GENERATED by tools/catalog.js, do not edit */\n' +
  '(function (root) {\n  const C = root.Curves = root.Curves || {};\n  C.catalog = ' +
  JSON.stringify({ built: new Date().toISOString().slice(0, 10), files: { figures: figureFiles, sections: sectionFiles }, figures, sections }, null, 1) +
  ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(ROOT, 'data', 'catalog.js'), out);
console.log('data/catalog.js: ' + figures.length + ' figures in ' + figureFiles.length + ' files, ' + sections.filter(s => s.hasText).length + '/' + sections.length + ' sections with text');
if (C.loadErrors.length) { C.loadErrors.forEach(e => console.error('LOAD ERROR ' + e.file + ': ' + e.error)); process.exit(1); }
