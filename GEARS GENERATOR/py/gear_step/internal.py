# Self-checks (docs/gear-math.md section 11) -- run directly: `python internal.py`
# --------------------------------------------------------------------------

def _selftest_addendum_inside_dedendum_outside():
    ip = InternalGearParams(z=40, module_mm=2.0)
    assert ip.addendum_radius < ip.pitch_radius < ip.dedendum_radius, \
        "internal gear: addendum must be INSIDE pitch radius, dedendum OUTSIDE -- inverted vs external"
    print(f"  [ok] da={2*ip.addendum_radius:.4f} d={2*ip.pitch_radius:.4f} df={2*ip.dedendum_radius:.4f} "
          f"(tip INSIDE pitch, root OUTSIDE -- the external-gear relationship inverted)")


def _selftest_rolling_contact_point_has_zero_relative_velocity():
    """The real content of the kinematics, and the check that actually pins
    the SIGN down: rolling without slip means the material point instantaneously
    at the contact location has ZERO velocity relative to the OTHER body's
    frame -- checked directly via finite difference, not assumed from the
    formula's construction."""
    R, rc = 40.0, 15.0
    eps = 1e-6
    x0, y0 = internal_point_to_ring_frame(-eps, 0.0, rc, rc, R)
    x1, y1 = internal_point_to_ring_frame(eps, 0.0, rc, rc, R)
    vx, vy = (x1 - x0) / (2 * eps), (y1 - y0) / (2 * eps)
    assert abs(vx) < 1e-6 and abs(vy) < 1e-6, (vx, vy)
    print(f"  [ok] contact point has zero relative velocity ({vx:.2e}, {vy:.2e}) -- true rolling, correct internal sign")


def _selftest_max_cutter_reach_equals_the_root_radius():
    """A cheap, independent sanity bound before trusting the expensive sweep:
    the farthest any swept cutter point gets from the ring axis must equal
    exactly the ring's own dedendum (root) radius -- the cutter's addendum
    (now playing the role of the ring's dedendum-cutter, see
    shaper_gear_params) reaches to exactly that depth and no farther, by
    construction of the swap."""
    ip = InternalGearParams(z=40, module_mm=2.0, cutter_teeth=20)
    gap = internal_gear_single_gap_swept(ip, n_phi=80, phi_margin=1.3)
    coords = list(gap.exterior.coords)
    max_r = max(math.hypot(x, y) for x, y in coords)
    assert abs(max_r - ip.dedendum_radius) < 1e-6, (max_r, ip.dedendum_radius)
    print(f"  [ok] max reach of the cutter tip = {max_r:.6f} == root radius {ip.dedendum_radius:.6f} exactly")


def _one_flank_offsets(ip: "InternalGearParams", n_phi: int = 400) -> list[float]:
    """Helper for both involute-matching tests below: isolate ONE tooth's
    ONE flank (the descending side, root-land to tip) and return
    ang - atan2(*involute_point(rb,t)) for each sample point on it -- a
    single involute flank should give an essentially constant value.

    Getting this window right matters: a tooth's two flanks are MIRROR
    images of each other, so naively filtering by a fixed angle range (the
    first version of this test did) can straddle the tip and mix samples
    from both flanks, which produces a smoothly-varying-but-wrong offset
    that looks like a real mismatch but isn't -- caught by plotting the
    actual boundary and seeing the tip sat inside the sampled range, not by
    guessing. Finding the tip explicitly (the minimum-radius point within a
    single-tooth window) and only sampling strictly before it sidesteps
    that entirely."""
    rb = ip.base_radius
    coords = internal_gear_outline(ip, simplify_tolerance_mm=0.0005, n_phi=n_phi)
    pitch_deg = 360.0 / ip.z
    # a window comfortably covering one full tooth (root-land to root-land)
    # without reaching into the NEXT tooth -- centered on the tooth roughly
    # at [0, pitch_deg], with a small margin on each side
    window = [(x, y) for x, y in coords if -0.5 < math.degrees(math.atan2(x, y)) < pitch_deg - 1.0]
    radii = [math.hypot(x, y) for x, y in window]
    if len(radii) < 10:
        return []
    tip_idx = min(range(len(radii)), key=lambda k: radii[k])

    lo, hi = ip.addendum_radius + 1.0, ip.dedendum_radius - 1.0
    offsets = []
    for k in range(0, tip_idx):
        x, y = window[k]
        r = radii[k]
        if lo < r < hi:
            ang = math.degrees(math.atan2(x, y))
            t = math.sqrt(max((r / rb) ** 2 - 1.0, 0.0))
            ix, iy = involute_point(rb, t)
            offsets.append(ang - math.degrees(math.atan2(ix, iy)))
    return offsets


def _selftest_generated_flank_matches_the_closed_form_involute():
    """The flank a real internal gear's shaper actually cuts must be a true
    involute of the SAME base circle formula (rb = R*cos(alpha)) an external
    gear uses -- checked by comparing many points along ONE generated flank
    against involute_point(rb, t) at the matching radius."""
    ip = InternalGearParams(z=40, module_mm=2.0, cutter_teeth=20)
    offsets = _one_flank_offsets(ip)
    assert len(offsets) >= 5, f"too few flank samples: {len(offsets)}"
    spread = max(offsets) - min(offsets)
    assert spread < 0.05, f"flank does not match a single involute to tolerance: spread={spread:.4f}deg"
    print(f"  [ok] generated flank matches the closed-form involute to {spread:.5f}deg over {len(offsets)} samples")


def _selftest_tooth_flank_shape_does_not_depend_on_the_construction_cutter_tooth_count():
    """The fundamental law of gearing: the GENERATED tooth flank shape must
    be independent of which cutter tooth count produced it (cutter_teeth is
    a construction parameter only -- docs/gear-math.md 11.2). Checked by
    generating the same ring with three different cutter_teeth values and
    confirming the flank-vs-involute offset (same measurement as the test
    above) agrees across all three, not just that each individually matches
    the involute."""
    means = []
    for zc in (15, 20, 26):
        ip = InternalGearParams(z=40, module_mm=2.0, cutter_teeth=zc)
        offsets = _one_flank_offsets(ip)
        assert len(offsets) >= 5, (zc, len(offsets))
        means.append(sum(offsets) / len(offsets))
    spread = max(means) - min(means)
    assert spread < 0.01, f"flank shape depends on cutter_teeth (it must not): spread={spread:.5f}deg, means={means}"
    print(f"  [ok] flank independent of cutter_teeth (15/20/26): spread={spread:.5f}deg")


