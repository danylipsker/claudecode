"""
Internal (ring / annulus) gears.

An internal gear has its teeth cut INTO an annular ring, pointing inward, and
meshes with an external pinion running inside it (same direction of
rotation for both -- unlike two external gears, which always turn opposite
ways; a well-known, real consequence of one pitch circle rolling inside the
other rather than outside it). See docs/gear-math.md section 11.

The involute flank math is identical to an external gear's (same base circle
rb = R*cos(alpha)), so the actual cutter tooth SHAPE is generated by reusing
`involute.single_tooth_polygon` completely unchanged -- exactly like bevel
gears reuse it for their own (non-integer-z) tooth. What's genuinely new
here is the GENERATING KINEMATICS: real internal gears are shaped, not
hobbed, with an external "shaper" cutter whose pitch circle rolls WITHOUT
SLIP along the INSIDE of the workpiece's pitch circle -- a different rolling
relationship than involute.py's rack-to-gear transform (which is an external/
infinite-radius case), so it needed its own derivation.

Both axes are fixed in space for shaping (unlike rack generation, where the
rack translates): center distance = R - rc (an internal mesh subtracts
radii, an external mesh adds them), and because rc < R the geometric contact
point is itself fixed in space too. Rolling without slip there requires
rc*theta_c = R*theta_w, with theta_c and theta_w having the SAME sign (the
same-rotation-direction fact above) -- checked directly, not assumed: the
actual verification is that a cutter-material point instantaneously AT the
contact location has zero velocity in the ring's own rotating frame (the
literal definition of rolling contact), confirmed numerically to float noise
before this module was built around the transform, not after.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, replace

from shapely.geometry import Polygon
from shapely.affinity import rotate as shapely_rotate
from shapely.ops import unary_union

from involute import GearParams, single_tooth_polygon, involute_point, involute_t_at_radius


@dataclass
class InternalGearParams:
    z: int                              # this ring gear's own tooth count
    module_mm: float
    pressure_angle_deg: float = 20.0
    addendum_coeff: float = 1.0         # ha* -- same meaning as GearParams, but addendum points INWARD here
    dedendum_coeff: float = 1.25        # hf* -- points OUTWARD here
    root_fillet_coeff: float = 0.38
    cutter_teeth: int = 0               # shaper cutter tooth count (construction param only); 0 = auto (z // 2)
    pinion_teeth: int = 0               # the mating external pinion, built and placed with the ring; 0 = none
    pinion_bore_diameter_mm: float = 0.0
    face_width_mm: float = 10.0
    rim_thickness_mm: float = 6.0       # solid material beyond the root (dedendum) circle, out to the outer rim
    backlash_mm: float = 0.0

    def __post_init__(self):
        if self.cutter_teeth <= 0:
            # A cutter roughly half the ring's size keeps the sweep angle
            # (in units of the RING's own pitch angle -- see
            # internal_gear_single_gap_swept) small and keeps the cutter's
            # own tooth count comfortably clear of its OWN undercut limit
            # for typical module/pressure-angle combinations -- a
            # reasonable, documented default, not a hard requirement (any
            # cutter_teeth < z works; the fundamental-law-of-gearing test in
            # tests/test_internal.py confirms the generated flank doesn't
            # depend on this choice at all).
            self.cutter_teeth = max(8, self.z // 2)

    @property
    def pressure_angle_rad(self) -> float:
        return math.radians(self.pressure_angle_deg)

    @property
    def pitch_radius(self) -> float:
        return self.module_mm * self.z / 2.0

    @property
    def base_radius(self) -> float:
        return self.pitch_radius * math.cos(self.pressure_angle_rad)

    @property
    def addendum_radius(self) -> float:
        """Tooth TIP circle -- smaller than the pitch radius (teeth point
        inward), the mirror of an external gear's own addendum_radius."""
        return self.pitch_radius - self.module_mm * self.addendum_coeff

    @property
    def dedendum_radius(self) -> float:
        """Tooth ROOT circle -- larger than the pitch radius."""
        return self.pitch_radius + self.module_mm * self.dedendum_coeff

    @property
    def outer_radius(self) -> float:
        return self.dedendum_radius + self.rim_thickness_mm

    def pinion_params(self) -> GearParams:
        """The mating external pinion: the same module, pressure angle,
        coefficients, backlash and face width as the ring, its own bore --
        an ordinary spur gear (involute.py), nothing swapped: it is the
        ring's addendum/dedendum that are inside out, not the pinion's."""
        return GearParams(
            z=self.pinion_teeth, module_mm=self.module_mm, pressure_angle_deg=self.pressure_angle_deg,
            addendum_coeff=self.addendum_coeff, dedendum_coeff=self.dedendum_coeff, root_fillet_coeff=self.root_fillet_coeff,
            backlash_mm=self.backlash_mm, face_width_mm=self.face_width_mm, bore_diameter_mm=self.pinion_bore_diameter_mm)

    @property
    def pinion_centre_distance(self) -> float:
        """R - r_p = m (z - z_p) / 2: the pinion's axis lies inside the ring's pitch circle."""
        return self.module_mm * (self.z - self.pinion_teeth) / 2.0

    def shaper_gear_params(self) -> GearParams:
        """The external shaper-cutter tooth, as an ordinary GearParams --
        SAME module/pressure-angle as this ring, but with addendum and
        dedendum coefficients SWAPPED: the cutter's own tip (its addendum)
        is what reaches all the way to the ring's DEEPEST cut (its
        dedendum, the farther-out root circle), and the cutter's own root
        (dedendum) is what stops short at the ring's addendum (tooth tip,
        the nearer-in circle) -- the exact same "cutter tip cuts the
        workpiece's dedendum" relationship involute.py's rack cutter has
        (rack_tip_depth uses dedendum_coeff, not addendum_coeff), just for
        a gear-shaped cutter instead of a rack-shaped one. Checked directly
        in tests/test_internal.py, not just asserted."""
        return GearParams(
            z=self.cutter_teeth,
            module_mm=self.module_mm,
            pressure_angle_deg=self.pressure_angle_deg,
            addendum_coeff=self.dedendum_coeff,
            dedendum_coeff=self.addendum_coeff,
            root_fillet_coeff=self.root_fillet_coeff,
            backlash_mm=self.backlash_mm,
        )


# --------------------------------------------------------------------------
# Generating transform: shaper cutter (pitch radius rc) rolling WITHOUT SLIP
# along the INSIDE of the ring's pitch circle (pitch radius R). See module
# docstring for the derivation and the zero-relative-velocity check.
# --------------------------------------------------------------------------

def internal_point_to_ring_frame(theta_w: float, px: float, py: float, rc: float, R: float) -> tuple[float, float]:
    """Cutter-local point (px, py) -- in the cutter's own body-fixed frame,
    same 'tooth centered on +Y' convention involute_point/single_tooth_polygon
    use -- mapped into the ring's body-fixed frame, at ring rotation angle
    theta_w (rad). Both axes fixed in space, offset by d = R - rc along +Y;
    contact point sits at (0, R) in the ring frame when theta_w = 0."""
    d = R - rc
    theta_c = (R / rc) * theta_w  # SAME sign as theta_w -- internal mesh turns both gears the same way
    ct, st = math.cos(theta_c), math.sin(theta_c)
    sx = ct * px - st * py
    sy = st * px + ct * py + d
    cw, sw = math.cos(theta_w), math.sin(theta_w)
    rx = cw * sx + sw * sy
    ry = -sw * sx + cw * sy
    return rx, ry


# --------------------------------------------------------------------------
# Swept cutter shape and full ring polygon (mirrors involute.py's
# rack_swept_cutter_union / full_gear_polygon structure closely)
# --------------------------------------------------------------------------

def internal_gear_single_gap_swept(ip: InternalGearParams, n_phi: int = 240, phi_margin: float = 0.7):
    """The shaper cutter's ONE tooth, swept across the theta_w range that
    carves a single tooth gap out of the ring, unioned into one polygon --
    the material-removal shape for one gap, in the RING's own frame. Same
    phi_margin convention as rack_swept_cutter_union: 0.7 pitch angles
    (measured in the RING's own pitch angle) is enough to fully carve one
    gap's fillet while staying inside this gap's angular territory when z
    copies are patterned around; isolated single-gap inspection wants a
    wider margin (e.g. 1.3)."""
    cutter_gp = ip.shaper_gear_params()
    tooth = single_tooth_polygon(cutter_gp, z_virtual=ip.cutter_teeth, n_phi=n_phi)
    pts = list(tooth.exterior.coords)
    if pts and pts[0] == pts[-1]:
        pts = pts[:-1]

    rc = cutter_gp.pitch_radius
    R = ip.pitch_radius
    pitch_ang = 2 * math.pi / ip.z
    theta_lo, theta_hi = -phi_margin * pitch_ang, phi_margin * pitch_ang

    polys = []
    for i in range(n_phi + 1):
        theta_w = theta_lo + (theta_hi - theta_lo) * i / n_phi
        coords = [internal_point_to_ring_frame(theta_w, px, py, rc, R) for (px, py) in pts]
        polys.append(Polygon(coords))
    return unary_union(polys)


def full_internal_gear_polygon(ip: InternalGearParams, n_phi: int = 240):
    """The complete internal-gear cross-section: an annulus from
    addendum_radius (tooth-tip circle, the bore-ward boundary) out to
    outer_radius, with all z tooth gaps cut by the (rotationally patterned)
    shaper-cutter sweep."""
    outer = Polygon([
        (ip.outer_radius * math.sin(2 * math.pi * i / 720), ip.outer_radius * math.cos(2 * math.pi * i / 720))
        for i in range(720)
    ])
    bore = Polygon([
        (ip.addendum_radius * math.sin(2 * math.pi * i / 720), ip.addendum_radius * math.cos(2 * math.pi * i / 720))
        for i in range(720)
    ])
    annulus = outer.difference(bore)

    one_gap = internal_gear_single_gap_swept(ip, n_phi=n_phi)
    pitch_deg = 360.0 / ip.z
    all_gaps = unary_union([
        shapely_rotate(one_gap, k * pitch_deg, origin=(0, 0))
        for k in range(ip.z)
    ])
    return annulus.difference(all_gaps)


def internal_gear_outer_outline(ip: InternalGearParams, simplify_tolerance_mm: float = 0.001,
                                 circle_segments: int = 360) -> list[tuple[float, float]]:
    """The ring's plain circular OUTER boundary (a build123d Face's outer
    wire wants this separately from the toothed inner wire -- see
    build_gear.build_internal_gear_solid)."""
    return [
        (ip.outer_radius * math.sin(2 * math.pi * i / circle_segments),
         ip.outer_radius * math.cos(2 * math.pi * i / circle_segments))
        for i in range(circle_segments)
    ]


def internal_gear_outline(ip: InternalGearParams, simplify_tolerance_mm: float = 0.001,
                           n_phi: int = 240) -> list[tuple[float, float]]:
    """The internal-tooth-and-bore boundary (the polygon's INNER ring, i.e.
    its hole) as an ordered list of (x, y) points -- the toothed edge a
    mating pinion would actually run against."""
    poly = full_internal_gear_polygon(ip, n_phi=n_phi)
    if poly.geom_type == "MultiPolygon":
        poly = max(poly.geoms, key=lambda g: g.area)
    inner = poly.interiors[0]
    ring = inner.simplify(simplify_tolerance_mm, preserve_topology=True) if simplify_tolerance_mm > 0 else inner
    coords = list(ring.coords)
    if coords and coords[0] == coords[-1]:
        coords = coords[:-1]
    return coords


