"""
Double-enveloping (globoid, Hindley / cone-drive type) worm and its throated
wheel. docs/gear-math.md section 18.

A cylindrical worm (worm.py) is a screw: its pitch surface is a cylinder and
the wheel touches it along a line at the throat only. A double-enveloping
worm is turned to WRAP the wheel: its pitch surface is the surface of
revolution, about the worm's axis, of the wheel's pitch circle -- an
hourglass whose radius at axial position z is

    r_p(z) = a - sqrt(r_g^2 - z^2),      a = r_w + r_g   (centre distance)

(r_w the worm's throat pitch radius, r_g = m z_g / 2 the wheel's), and its
tip and root surfaces are the same revolve of the circles r_g - h_a and
r_g + h_f about the wheel centre. The wheel is in turn throated around
the worm, and the two envelope each other: every thread turn is in mesh,
not just the throat.

THREAD FLANKS (Hindley's construction, exact). The worm is generated by a
straight-edged tool fixed to the wheel: in the central plane (the axial
plane of the worm through the wheel centre C) a wheel tooth's flank is a
straight line at the pressure angle alpha to the radial direction from C,
tangent to the base circle rho_b = r_g sin(alpha) about C. As the worm
turns by theta_w the wheel turns by theta_g = theta_w z_w / z_g about its
own axis, which is perpendicular to the central plane, so the line stays
in that plane and merely rotates about C. In the worm's frame the central
plane is the axial plane at angle phi = -theta_w, and in it the thread
space is the wheel's tooth space at wheel angle beta = phi z_w / z_g
(right hand) -- a region between two such lines, cut off by the tip and
root circles about C. So every axial section of the worm is an explicit
polygon: two straight flanks (the two teeth's facing flanks), a tip arc
and a root arc, all about C; the thread of one start is the loft of that
section through the angle range in which its wheel space crosses the
worm's length -- one space's passage IS the whole thread, over as many
worm turns as the wrap takes. A thread's tip is the hourglass tip
surface; its root side is extended a little into the core so the fuse has
material to join, no coincident faces.

    In the axial plane (z along the worm axis, r from the worm axis) with
    C = (0, a), a point at wheel angle gamma (0 = toward the worm axis,
    positive toward +z) and distance rho from C is
        z = rho sin(gamma),   r = a - rho cos(gamma).

At the throat (z = 0, the central plane) the section is the standard
straight-sided trapezoid of the cylindrical worm's ZA thread -- thickness
pi m / 2 at the pitch radius, flanks at alpha -- which the tests check;
away from the throat the flanks tilt with the wheel angle, which is what
makes every turn conjugate to the wheel.

WRAP AND LENGTH. The worm spans `envelope_teeth` wheel pitches (4 by
default): the wrap angle about C is 2 pi envelope_teeth / z_g and the
worm's length L = 2 r_g sin(wrap / 2). The wheel's face width default is
2 (r_w - h_a) sin(60 deg)... (the throat arc of the wheel's tip, radius
r_w - h_a about the worm axis, spans +-60 deg).

THE WHEEL (section 18.2) is generated FROM the built worm, the way the
face gear is from its shaper: the worm is the hob. Each transverse station
of the wheel (a plane perpendicular to the wheel axis at height h) gets
the union of the worm's sections by that plane over the generating
motion -- the worm turning about its axis while revolving about the wheel
axis at the ratio -- and those sections come from a tessellation of the
worm solid sliced by the plane (fast numpy on the triangle mesh); the
tooth space is a loft through the stations, patterned and cut from a
throated blank, exactly as face_gear.py does. The pair check is the
same too: the worm meshes through the built wheel with only sliver
overlap at several phases and collides when turned half a pitch.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np
import build123d as bd

from involute import GearParams


@dataclass
class GloboidWormParams:
    starts: int                         # z_w: thread starts
    wheel_teeth: int                    # z_g
    axial_module_mm: float = 2.0        # m at the throat (axial pitch pi m)
    pitch_diameter_mm: float = 24.0     # d_w: the worm's throat pitch diameter
    pressure_angle_deg: float = 20.0    # of the straight-line generatrix
    addendum_coeff: float = 1.0
    dedendum_coeff: float = 1.25
    envelope_teeth: float = 4.0         # wheel pitches the worm wraps (sets its length)
    hand: str = "right"
    bore_diameter_mm: float = 0.0
    wheel_face_width_mm: float = 0.0    # 0 = auto
    wheel_bore_diameter_mm: float = 0.0

    # ---- sizes ----
    @property
    def module(self) -> float:
        return self.axial_module_mm

    @property
    def pitch_radius(self) -> float:
        """r_w: the worm's pitch radius at the throat."""
        return self.pitch_diameter_mm / 2.0

    @property
    def wheel_pitch_radius(self) -> float:
        return self.axial_module_mm * self.wheel_teeth / 2.0

    @property
    def centre_distance(self) -> float:
        return self.pitch_radius + self.wheel_pitch_radius

    @property
    def addendum(self) -> float:
        return self.addendum_coeff * self.axial_module_mm

    @property
    def dedendum(self) -> float:
        return self.dedendum_coeff * self.axial_module_mm

    @property
    def pressure_angle_rad(self) -> float:
        return math.radians(self.pressure_angle_deg)

    @property
    def ratio(self) -> float:
        return self.wheel_teeth / self.starts

    @property
    def lead_angle_rad(self) -> float:
        """At the throat, as for a cylindrical worm: tan(lambda) = z_w m / d_w."""
        return math.atan2(self.starts * self.axial_module_mm, self.pitch_diameter_mm)

    @property
    def wrap_angle_rad(self) -> float:
        """The angle the worm subtends about the wheel centre."""
        return 2.0 * math.pi * self.envelope_teeth / self.wheel_teeth

    @property
    def length(self) -> float:
        """L = 2 r_g sin(wrap / 2): the chord of the wrap on the wheel's pitch circle."""
        return 2.0 * self.wheel_pitch_radius * math.sin(0.5 * self.wrap_angle_rad)

    @property
    def wheel_face_width(self) -> float:
        if self.wheel_face_width_mm > 0:
            return self.wheel_face_width_mm
        return 2.0 * (self.pitch_radius - self.addendum) * math.sin(math.radians(60.0))

    @property
    def tip_rho(self) -> float:
        """Distance from the wheel centre of the worm's tip surface (it clears the wheel root)."""
        return self.wheel_pitch_radius - self.addendum

    @property
    def root_rho(self) -> float:
        """Distance from the wheel centre of the worm's root surface (the wheel's tip clears it)."""
        return self.wheel_pitch_radius + self.dedendum

    def pitch_radius_at(self, z: float) -> float:
        return self.centre_distance - math.sqrt(max(0.0, self.wheel_pitch_radius ** 2 - z * z))

    def tip_radius_at(self, z: float) -> float:
        return self.centre_distance - math.sqrt(max(0.0, self.tip_rho ** 2 - z * z))

    def root_radius_at(self, z: float) -> float:
        return self.centre_distance - math.sqrt(max(0.0, self.root_rho ** 2 - z * z))

    @property
    def base_rho(self) -> float:
        """The flank lines are tangent to this circle about the wheel centre."""
        return self.wheel_pitch_radius * math.sin(self.pressure_angle_rad)

    @property
    def tooth_half_angle(self) -> float:
        """Half the wheel tooth's thickness at its pitch circle, as an angle about C
        (thickness pi m / 2: the standard split of the pitch)."""
        return (math.pi * self.axial_module_mm / 4.0) / self.wheel_pitch_radius

    def wheel_gear_params(self) -> GearParams:
        """The wheel's nominal proportions as a GearParams (module, teeth,
        pressure angle) for the derived-values display; the wheel solid
        itself is generated from the worm (section 18.2)."""
        return GearParams(z=self.wheel_teeth, module_mm=self.axial_module_mm,
                          pressure_angle_deg=self.pressure_angle_deg, addendum_coeff=self.addendum_coeff,
                          dedendum_coeff=self.dedendum_coeff, face_width_mm=self.wheel_face_width)


# ---- the axial-plane geometry about the wheel centre ----

def _wheel_point(gp: GloboidWormParams, gamma: float, rho: float) -> tuple[float, float]:
    """(z, r) of the point at wheel angle gamma and distance rho from C."""
    return rho * math.sin(gamma), gp.centre_distance - rho * math.cos(gamma)


def flank_line(gp: GloboidWormParams, gamma_pitch: float, sign: int):
    """The straight flank through the pitch point at wheel angle gamma_pitch,
    leaning by the pressure angle toward smaller gamma (sign = -1) or
    larger gamma (sign = +1) as it goes outward from C. Returns (point,
    direction) in (z, r)."""
    a = gp.pressure_angle_rad
    u = (math.sin(gamma_pitch), -math.cos(gamma_pitch))          # radial, away from C
    e = (math.cos(gamma_pitch), math.sin(gamma_pitch))           # tangential, toward +gamma
    d = (math.cos(a) * u[0] + sign * math.sin(a) * e[0], math.cos(a) * u[1] + sign * math.sin(a) * e[1])
    p = _wheel_point(gp, gamma_pitch, gp.wheel_pitch_radius)
    return p, d


def _line_circle(gp: GloboidWormParams, p, d, rho: float) -> tuple[float, float]:
    """The point of the line p + t d (p the pitch point, d outward from C)
    at distance rho from C, on the pitch point's side: the line crosses
    every circle about C twice, once near the pitch point (|t| about the
    tooth height) and once far round on the other side of C (|t| about
    2 r_g), so take the root of smallest |t|."""
    cz, cr = 0.0, gp.centre_distance
    fz, fr = p[0] - cz, p[1] - cr
    b = 2.0 * (fz * d[0] + fr * d[1])
    c = fz * fz + fr * fr - rho * rho
    disc = b * b - 4.0 * c
    if disc < 0:
        raise ValueError("globoid worm: flank line misses the circle rho = %.3f" % rho)
    s = math.sqrt(disc)
    t = min(((-b + s) / 2.0, (-b - s) / 2.0), key=abs)
    return p[0] + t * d[0], p[1] + t * d[1]


def thread_section(gp: GloboidWormParams, beta: float, n_arc: int = 8, root_overlap_mm: float = 0.3):
    """One start's thread section in an axial plane, as the wheel's tooth
    space centred at wheel angle beta: the facing flanks of the teeth at
    beta -/+ pi/z_g, between the tip circle (rho = r_g - h_a) and the root
    circle (rho = r_g + h_f) about C, the root side extended root_overlap_mm
    into the core. Closed polygon of 2 (n_arc + 1) points in (z, r):
    tip arc (lower flank to upper), upper flank outward, root arc back,
    lower flank inward."""
    half_pitch = math.pi / gp.wheel_teeth
    psi = gp.tooth_half_angle
    # A wheel tooth narrows outward from C (toward its tip, which lies at the
    # worm's root), so each flank leans toward its own tooth's centreline as
    # it goes outward: the lower tooth's upper flank toward smaller gamma,
    # the upper tooth's lower flank toward larger gamma. The space between
    # them -- the thread -- is therefore wide at the worm's root and narrow
    # at its tip, as a thread should be. (The first draft had these two
    # signs swapped and built an upside-down thread; the section probe
    # showed it: +-2.2 mm wide at the tip, +-0.7 at the root.)
    lower_p, lower_d = flank_line(gp, beta - half_pitch + psi, -1)   # the lower tooth's upper flank
    upper_p, upper_d = flank_line(gp, beta + half_pitch - psi, +1)   # the upper tooth's lower flank
    rho_tip, rho_root = gp.tip_rho, gp.root_rho + root_overlap_mm
    a_tip = _line_circle(gp, lower_p, lower_d, rho_tip)
    b_tip = _line_circle(gp, upper_p, upper_d, rho_tip)
    b_root = _line_circle(gp, upper_p, upper_d, rho_root)
    a_root = _line_circle(gp, lower_p, lower_d, rho_root)

    def arc(p0, p1, rho, n):
        g0 = math.atan2(p0[0], gp.centre_distance - p0[1])
        g1 = math.atan2(p1[0], gp.centre_distance - p1[1])
        return [_wheel_point(gp, g0 + (g1 - g0) * i / n, rho) for i in range(n + 1)]

    pts = arc(a_tip, b_tip, rho_tip, n_arc)            # tip arc, lower to upper (includes both corners)
    pts += arc(b_root, a_root, rho_root, n_arc)        # root arc, upper to lower
    return pts


def thread_beta_range(gp: GloboidWormParams, margin_rad: float | None = None) -> tuple[float, float]:
    """The wheel angles over which a space crosses the worm's length (its
    section's z-extent reaches the ends), plus a margin."""
    half_wrap = 0.5 * gp.wrap_angle_rad
    if margin_rad is None:
        # the section spans about a pitch either side of its centre at the root circle
        margin_rad = math.pi / gp.wheel_teeth + 0.05
    return -half_wrap - margin_rad, half_wrap + margin_rad


def thread_stations(gp: GloboidWormParams, start_index: int = 0, n_per_turn: int = 48):
    """3D stations (lists of points) of one thread start: its wheel space
    (index start_index at phi = 0) carried through the wrap. Axis = +Z, the
    wheel centre on +X at the centre distance, right hand: the space moves
    toward +z as the axial plane angle phi increases."""
    ratio = gp.starts / gp.wheel_teeth
    sign = 1.0 if gp.hand != "left" else -1.0
    beta0 = 2.0 * math.pi * start_index / gp.wheel_teeth
    b_lo, b_hi = thread_beta_range(gp)
    # beta(phi) = beta0 + sign * phi * ratio  ->  phi over the range that sweeps beta through [b_lo, b_hi]
    phi_a = (b_lo - beta0) / (sign * ratio)
    phi_b = (b_hi - beta0) / (sign * ratio)
    if phi_a > phi_b:
        phi_a, phi_b = phi_b, phi_a
    turns = (phi_b - phi_a) / (2.0 * math.pi)
    n = max(8, int(math.ceil(turns * n_per_turn)))
    stations = []
    for i in range(n + 1):
        phi = phi_a + (phi_b - phi_a) * i / n
        beta = beta0 + sign * phi * ratio
        sec = thread_section(gp, beta)
        c, s = math.cos(phi), math.sin(phi)
        stations.append([(r * c, r * s, z) for (z, r) in sec])
    return stations


def worm_core_solid(gp: GloboidWormParams) -> bd.Part:
    """The hourglass core: the root surface of revolution between the end
    faces, bored if asked."""
    n = 48
    half = 0.5 * gp.length
    prof = [(gp.root_radius_at(-half + gp.length * i / n), -half + gp.length * i / n) for i in range(n + 1)]
    r_in = gp.bore_diameter_mm / 2.0
    pts = [(r_in, -half)] + prof + [(r_in, half)]
    with bd.BuildPart() as part:
        with bd.BuildSketch(bd.Plane.XZ):
            with bd.BuildLine():
                bd.Polyline(*pts, pts[0])
            bd.make_face()
        bd.revolve(axis=bd.Axis.Z, revolution_arc=360)
    return part.part


def build_globoid_worm_solid(gp: GloboidWormParams, n_per_turn: int = 48) -> bd.Solid:
    """Core plus one smooth loft per start (ThruSections through the
    rotated stations with compatibility checking off, as the spiral bevel:
    18 faces per thread instead of one facet per station edge, and the
    true swept volume where the ruled loft cuts chords), fused in one
    N-ary fuse as the cylindrical worm, trimmed to the worm's length by
    its end planes."""
    from spiral_bevel import loft_through_stations
    core = worm_core_solid(gp)
    threads = [loft_through_stations(thread_stations(gp, k, n_per_turn), ruled=False) for k in range(gp.starts)]
    worm = core.fuse(*threads)
    half = 0.5 * gp.length
    envelope = bd.Solid.make_cylinder(gp.centre_distance, gp.length, bd.Plane((0, 0, -half)))
    trimmed = worm.intersect(envelope)
    if isinstance(trimmed, bd.ShapeList):
        trimmed = bd.Compound(children=list(trimmed))
    solids = trimmed.solids()
    if len(solids) != 1:
        raise RuntimeError(f"globoid worm: {len(solids)} solids after trimming, expected one")
    return solids[0]
