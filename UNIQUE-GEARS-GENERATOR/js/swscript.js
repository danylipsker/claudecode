/* swscript.js - writes a self-contained PowerShell script that drives an
 * installed SOLIDWORKS and saves real .sldprt and .sldasm files.
 *
 * .sldprt and .sldasm are proprietary binary formats with no published
 * specification; nothing but SOLIDWORKS itself can write them. So the browser
 * writes a script instead, with the STEP bodies embedded in it, and
 * SOLIDWORKS does the saving.
 *
 * Everything below was settled by running it against SOLIDWORKS 2020 on a
 * real machine, not from the documentation:
 *
 *  - SOLIDWORKS automation is STA. Windows PowerShell already is; PowerShell 7
 *    is MTA, so the script re-launches itself with -STA.
 *  - PowerShell cannot hold a SOLIDWORKS object. Late binding fails at
 *    activation with TYPE_E_ELEMENTNOTFOUND, because PowerShell's COM adapter
 *    eagerly reads type information the interface will not give it. Compiling
 *    a small C# helper against the SOLIDWORKS interop assemblies works, so all
 *    COM calls live in that class and the live handles stay in static fields:
 *    an object handed back to PowerShell arrives as a bare System.__ComObject
 *    that will not convert to ISldWorks again.
 *  - LoadFile4 returns before the translator has finished building the body.
 *    Saving straight away writes an EMPTY part, so the script waits for a body
 *    to appear. The wait is on the PowerShell side, which keeps the C# free of
 *    any threading assembly (System.Threading.Thread is not referenced by
 *    default on .NET Core).
 *  - GetBodies2 must be asked for ALL bodies, not visible ones: immediately
 *    after an import the body exists but is not yet flagged visible.
 *  - AddComponent5 positions a component by its bounding-box CENTRE, which
 *    drops it by half its thickness and misses the centre distance by microns,
 *    so the component transforms are set outright afterwards.
 *  - SOLIDWORKS fixes only the first component; both get fixed here.
 *  - Importing with 3D Interconnect on makes a linked feature and pops a
 *    template dialog; off, the classic translator brings in a native body.
 *    That toggle and two others are set for the import and restored after.
 *
 * The generated text is deliberately ASCII only: Windows PowerShell 5.1 reads
 * a .ps1 as ANSI unless it carries a BOM, and a downloaded file has none.
 */
'use strict';

/** PowerShell single-quoted string escape. */
function psq(s) { return String(s).replace(/'/g, "''"); }

/** Strip anything a PowerShell 5.1 ANSI read would mangle. */
function ascii(s) {
  return String(s)
    .replace(/[‘’]/g, "'").replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-').replace(/…/g, '...')
    .replace(/×/g, 'x').replace(/°/g, ' deg').replace(/∅/g, 'dia ')
    .replace(/[^\x09\x0a\x0d\x20-\x7e]/g, '');
}

/**
 * @param {object} o
 *   o.gear1Step, o.gear2Step  STEP text for each body, each about its own origin
 *   o.centreDistanceMM        where gear 2's axle goes
 *   o.baseName                file stem
 *   o.summary                 one line describing the pair
 */
function buildSolidWorksScript(o) {
  const base = ascii(o.baseName);
  const head = [
    '<#',
    '    ' + base + ' - SOLIDWORKS builder',
    '    Generated by Unique Gears (conjugate shape workbench).',
    '',
    '    ' + ascii(o.summary),
    '',
    '    WHAT IT DOES',
    '      1. writes the two gear bodies next to this script as STEP files',
    '      2. imports each one and saves it as a .sldprt',
    '      3. builds an assembly with the two parts a centre distance apart,',
    '         already in mesh, both fixed, and saves it as a .sldasm',
    '',
    '    HOW TO RUN IT',
    '      Right-click this file and pick "Run with PowerShell", or:',
    '',
    '        powershell -ExecutionPolicy Bypass -File "' + base + '.ps1"',
    '',
    '      SOLIDWORKS does not have to be open; the script will start it.',
    '      If Windows refuses to run the file because it came from a browser:',
    '',
    '        Unblock-File "' + base + '.ps1"',
    '',
    '    OPTIONS',
    '      -OutputFolder <path>   where to put the files (default: next to this script)',
    '      -NoAssembly            save the two parts only',
    '      -KeepStep              keep the intermediate STEP files (they are kept by default)',
    '#>',
    ''
  ].join('\n');

  const body = String.raw`
[CmdletBinding()]
param(
    [string] $OutputFolder,
    [switch] $NoAssembly,
    [switch] $CloseWhenDone
)

$ErrorActionPreference = 'Stop'

# ---- SOLIDWORKS automation is STA. Windows PowerShell is; pwsh is not. ------
if ([Threading.Thread]::CurrentThread.GetApartmentState() -ne 'STA') {
    Write-Host 'Re-launching in a single-threaded apartment (SOLIDWORKS requires STA)...' -ForegroundColor DarkGray
    $exe = (Get-Process -Id $PID).Path
    $relaunch = @('-STA','-NoProfile','-ExecutionPolicy','Bypass','-File',$PSCommandPath)
    if ($OutputFolder)  { $relaunch += @('-OutputFolder', $OutputFolder) }
    if ($NoAssembly)    { $relaunch += '-NoAssembly' }
    if ($CloseWhenDone) { $relaunch += '-CloseWhenDone' }
    & $exe @relaunch
    exit $LASTEXITCODE
}

# $PSScriptRoot is not available while parameter defaults are bound, so the
# fallback happens here instead.
if (-not $OutputFolder) {
    if ($PSScriptRoot) { $OutputFolder = $PSScriptRoot } else { $OutputFolder = (Get-Location).Path }
}
New-Item -ItemType Directory -Force -Path $OutputFolder | Out-Null

# ---- find the SOLIDWORKS interop assemblies --------------------------------
$searchDirs = @()
# Read via GetEnvironmentVariable on purpose: the brace-wrapped env-var
# syntax would be read as an interpolation by the generator writing this file.
$pf86 = [Environment]::GetEnvironmentVariable('ProgramFiles(x86)')
foreach ($base in @("$env:ProgramFiles\SOLIDWORKS Corp", "$pf86\SOLIDWORKS Corp")) {
    if (Test-Path $base) {
        $searchDirs += (Get-ChildItem $base -Directory -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName })
    }
}
$searchDirs += "$env:ProgramFiles\Common Files\SOLIDWORKS Shared"
$refs = $null
foreach ($d in $searchDirs) {
    $a = Join-Path $d 'SolidWorks.Interop.sldworks.dll'
    $b = Join-Path $d 'SolidWorks.Interop.swconst.dll'
    if ((Test-Path $a) -and (Test-Path $b)) { $refs = @($a, $b); break }
}
if (-not $refs) {
    throw 'Could not find SolidWorks.Interop.sldworks.dll. Is SOLIDWORKS installed on this machine?'
}
Write-Host ("interop: " + $refs[0]) -ForegroundColor DarkGray

$global:UgSwRefs = $refs
foreach ($r in $refs) { $null = [Reflection.Assembly]::LoadFrom($r) }
[AppDomain]::CurrentDomain.add_AssemblyResolve([ResolveEventHandler]{
    param($sender, $e)
    $short = $e.Name.Split(',')[0]
    foreach ($r in $global:UgSwRefs) {
        if ([IO.Path]::GetFileNameWithoutExtension($r) -eq $short) { return [Reflection.Assembly]::LoadFrom($r) }
    }
    return $null
})
`;

  const csharp = String.raw`
$cs = @'
using System;
using System.IO;
using SolidWorks.Interop.sldworks;

// All COM work lives here. A SOLIDWORKS object handed back to PowerShell
// arrives as a bare System.__ComObject that will not convert to ISldWorks
// again, so the live handles stay in static fields and PowerShell exchanges
// only strings and numbers with this class.
public static class UgSwBuild
{
    const int TOGGLE_DEFAULT_TEMPLATES = 111;
    const int TOGGLE_INTERCONNECT      = 691;
    const int TOGGLE_MULTIBODY_PARTS   = 220;
    const int STR_TEMPLATE_ASSEMBLY    = 9;

    static ISldWorks _sw;
    static ModelDoc2 _doc;
    static bool _oldDefaults, _oldInter, _oldMulti, _prefsHeld;

    public static string Connect()
    {
        Type t = Type.GetTypeFromProgID("SldWorks.Application");
        if (t == null) throw new Exception("SldWorks.Application is not registered on this machine.");
        _sw = (ISldWorks)Activator.CreateInstance(t);
        _sw.Visible = true;
        return _sw.RevisionNumber();
    }

    public static string HoldImportPrefs()
    {
        _oldDefaults = _sw.GetUserPreferenceToggle(TOGGLE_DEFAULT_TEMPLATES);
        _oldInter    = _sw.GetUserPreferenceToggle(TOGGLE_INTERCONNECT);
        _oldMulti    = _sw.GetUserPreferenceToggle(TOGGLE_MULTIBODY_PARTS);
        _prefsHeld = true;
        if (!_oldDefaults) _sw.SetUserPreferenceToggle(TOGGLE_DEFAULT_TEMPLATES, true);
        if (_oldInter)     _sw.SetUserPreferenceToggle(TOGGLE_INTERCONNECT, false);
        if (_oldMulti)     _sw.SetUserPreferenceToggle(TOGGLE_MULTIBODY_PARTS, false);
        return "defaults=" + _oldDefaults + " 3dInterconnect=" + _oldInter + " multibodyAsParts=" + _oldMulti;
    }

    public static void ReleaseImportPrefs()
    {
        if (!_prefsHeld) return;
        if (!_oldDefaults) _sw.SetUserPreferenceToggle(TOGGLE_DEFAULT_TEMPLATES, false);
        if (_oldInter)     _sw.SetUserPreferenceToggle(TOGGLE_INTERCONNECT, true);
        if (_oldMulti)     _sw.SetUserPreferenceToggle(TOGGLE_MULTIBODY_PARTS, true);
        _prefsHeld = false;
    }

    public static void BeginImport(string stepPath)
    {
        int errors = 0;
        _doc = _sw.LoadFile4(stepPath, "r", null, ref errors);
        if (_doc == null)
            throw new Exception("SOLIDWORKS could not import " + stepPath + " (error " + errors + ").");
    }

    // VisibleOnly must be false: straight after an import the body exists but
    // is not yet flagged visible, and the visible-only call returns nothing.
    public static int Bodies()
    {
        PartDoc pd = _doc as PartDoc;
        if (pd == null) return -1;
        object[] b = pd.GetBodies2(0, false) as object[];
        return (b == null) ? 0 : b.Length;
    }

    public static int Surfaces()
    {
        PartDoc pd = _doc as PartDoc;
        if (pd == null) return 0;
        object[] b = pd.GetBodies2(2, false) as object[];   // swSheetBody
        return (b == null) ? 0 : b.Length;
    }

    public static void Rebuild() { if (_doc != null) _doc.EditRebuild3(); }

    public static string SaveCurrent(string path)
    {
        if (File.Exists(path)) File.Delete(path);
        int err = 0, warn = 0;
        bool ok = _doc.Extension.SaveAs(path, 0, 1, null, ref err, ref warn);
        if (!ok || !File.Exists(path)) ok = _doc.SaveAs4(path, 0, 1, ref err, ref warn);
        if (!File.Exists(path)) throw new Exception("SOLIDWORKS would not save " + path + " (error " + err + ").");
        return new FileInfo(path).Length.ToString();
    }

    public static string BuildAssembly(string part1, string part2, string asmPath, double centreMM)
    {
        string tpl = _sw.GetUserPreferenceStringValue(STR_TEMPLATE_ASSEMBLY);
        if (String.IsNullOrEmpty(tpl) || !File.Exists(tpl))
            throw new Exception("SOLIDWORKS has no assembly template configured, so no assembly can be made. The parts were saved.");
        object created = _sw.NewDocument(tpl, 0, 0, 0);
        if (created == null) throw new Exception("SOLIDWORKS would not create an assembly from " + tpl + ".");
        AssemblyDoc asm = (AssemblyDoc)_sw.ActiveDoc;
        ModelDoc2 asmModel = (ModelDoc2)asm;

        // the part documents must stay open: AddComponent5 refuses a part whose
        // document is not loaded
        Component2 c1 = asm.AddComponent5(part1, 0, "", false, "", 0.0, 0.0, 0.0);
        Component2 c2 = asm.AddComponent5(part2, 0, "", false, "", centreMM / 1000.0, 0.0, 0.0);
        if (c1 == null || c2 == null)
            throw new Exception("SOLIDWORKS would not insert the parts into the assembly.");

        // AddComponent5 places by bounding-box centre; set the transforms outright
        MathUtility mu = (MathUtility)_sw.GetMathUtility();
        Place(mu, c1, 0.0);
        Place(mu, c2, centreMM / 1000.0);

        asmModel.ClearSelection2(true);
        c1.Select4(true, null, false);
        c2.Select4(true, null, false);
        asm.FixComponent();
        asmModel.ClearSelection2(true);

        asmModel.EditRebuild3();
        asmModel.ViewZoomtofit2();

        _doc = asmModel;
        return SaveCurrent(asmPath);
    }

    static void Place(MathUtility mu, Component2 c, double x)
    {
        double[] d = new double[16];
        d[0] = 1; d[4] = 1; d[8] = 1;   // identity rotation, row major
        d[9] = x;                       // translation, metres
        d[12] = 1;                      // scale
        c.Transform2 = (MathTransform)mu.CreateTransform(d);
    }

    public static void CloseAll() { if (_sw != null) _sw.CloseAllDocuments(true); }
}
'@
Add-Type -TypeDefinition $cs -ReferencedAssemblies $refs -ErrorAction Stop
`;

  const run = String.raw`
function Import-Gear([string] $StepPath, [string] $PartPath) {
    [UgSwBuild]::BeginImport($StepPath)
    # LoadFile4 returns before the translator has built the body; saving now
    # would write an empty part.
    $n = 0
    for ($i = 0; $i -lt 200; $i++) {
        $n = [UgSwBuild]::Bodies()
        if ($n -ne 0) { break }
        Start-Sleep -Milliseconds 150
        if ($i % 10 -eq 9) { [UgSwBuild]::Rebuild() }
    }
    if ($n -le 0) {
        $surf = [UgSwBuild]::Surfaces()
        throw ("SOLIDWORKS imported " + [IO.Path]::GetFileName($StepPath) + " as " + $surf +
               " loose surface(s) instead of a solid. Re-export with the curved wall switched OFF, " +
               "or with more profile points.")
    }
    $bytes = [UgSwBuild]::SaveCurrent($PartPath)
    Write-Host ("  " + [IO.Path]::GetFileName($PartPath) + "  (" + ("{0:N0}" -f [int]$bytes) + " bytes, " + $n + " solid body)") -ForegroundColor Green
}

$step1 = Join-Path $OutputFolder "$Base-1.step"
$step2 = Join-Path $OutputFolder "$Base-2.step"
$part1 = Join-Path $OutputFolder "$Base-1.sldprt"
$part2 = Join-Path $OutputFolder "$Base-2.sldprt"
$asm   = Join-Path $OutputFolder "$Base.sldasm"

Set-Content -Path $step1 -Value $Gear1Step -Encoding ascii
Set-Content -Path $step2 -Value $Gear2Step -Encoding ascii
Write-Host ("STEP written to " + $OutputFolder) -ForegroundColor DarkGray

Write-Host ("SOLIDWORKS " + [UgSwBuild]::Connect() + " connected.") -ForegroundColor DarkGray
Write-Host ("settings were: " + [UgSwBuild]::HoldImportPrefs()) -ForegroundColor DarkGray
try {
    Import-Gear $step1 $part1
    Import-Gear $step2 $part2
} finally {
    [UgSwBuild]::ReleaseImportPrefs()
}

if (-not $NoAssembly) {
    $bytes = [UgSwBuild]::BuildAssembly($part1, $part2, $asm, $CentreDistanceMM)
    Write-Host ("  " + [IO.Path]::GetFileName($asm) + "  (" + ("{0:N0}" -f [int]$bytes) + " bytes, 2 components, both fixed)") -ForegroundColor Green
}

if ($CloseWhenDone) { [UgSwBuild]::CloseAll() }

Write-Host ''
Write-Host ("Done. Centre distance " + $CentreDistanceMM + " mm.") -ForegroundColor Cyan
Write-Host ("  " + $part1)
Write-Host ("  " + $part2)
if (-not $NoAssembly) { Write-Host ("  " + $asm) }
`;

  const data = [
    '# ============================== the geometry ==============================',
    "$CentreDistanceMM = " + o.centreDistanceMM,
    "$Base = '" + psq(base) + "'",
    '',
    "$Gear1Step = @'",
    o.gear1Step.replace(/\r/g, '').replace(/\n$/, ''),
    "'@",
    '',
    "$Gear2Step = @'",
    o.gear2Step.replace(/\r/g, '').replace(/\n$/, ''),
    "'@",
    ''
  ].join('\n');

  const text = [head, body, data, csharp, run].join('\n');
  return ascii(text).replace(/\n/g, '\r\n');
}
